const MARKS: Record<string, (w: number) => [number, number][]> = {
  '́': (w) => [[Math.ceil(w / 2), -2], [Math.ceil(w / 2) - 1, -1]],
  '̀': (w) => [[Math.floor(w / 2) - 1, -2], [Math.floor(w / 2), -1]],
  '̂': (w) => [[Math.floor(w / 2) - 1, -2], [Math.ceil(w / 2), -2], [0, -1], [w - 1, -1]],
  '̈': (w) => [[0, -2], [w - 1, -2]],
  '̧': (w) => [[Math.floor(w / 2), 7], [Math.floor(w / 2) - 1, 8]],
};

export interface BlockRect {
  x: number;
  y: number;
  w: number;
  h: number;
}

/** Returns rects in cell units (cap height = 7 cells). */
export function layoutBlocks(text: string, tracking = 1, space = 3) {
  const rects: BlockRect[] = [];
  let x = 0;
  const list = [...text.toUpperCase().normalize('NFD')];
  for (let i = 0; i < list.length; i++) {
    const c = list[i];
    if (MARKS[c]) continue;
    const g = B[c];
    if (!g) {
      x += space;
      continue;
    }
    const rows = g.split('|');
    const w = rows[0].length;
    rows.forEach((row, y) => {
      let run = -1;
      for (let k = 0; k <= w; k++) {
        if (row[k] === '#') {
          if (run < 0) run = k;
        } else if (run >= 0) {
          rects.push({ x: x + run, y, w: k - run, h: 1 });
          run = -1;
        }
      }
    });
    let j = i + 1;
    while (j < list.length && MARKS[list[j]]) {
      for (const [mx, my] of MARKS[list[j++]](w)) rects.push({ x: x + mx, y: my, w: 1, h: 1 });
    }
    x += w + tracking;
  }
  return { rects, width: Math.max(0, x - tracking) };
}
